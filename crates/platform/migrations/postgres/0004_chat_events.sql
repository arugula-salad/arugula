-- 0004: chat's live events, numbered (M144): what each live stream is sent,
-- kept a while so a page that dropped resumes after the last one it had
-- (`Last-Event-ID`), on whichever of the platform's machines it reaches.
-- Each machine is woken by `pg_notify` when one is added, and reads those
-- after the last it sent. They're added one at a time (the `chat_events`
-- lock), so they commit in `seq` order and a reader never passes one that
-- isn't committed yet. `seq` is given by default so M145 can copy SQLite's.
CREATE TABLE chat_events (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT COLLATE pg_c_utf8 NOT NULL,
    body TEXT COLLATE pg_c_utf8 NOT NULL,
    to_account TEXT COLLATE pg_c_utf8,
    at BIGINT NOT NULL
);
CREATE INDEX chat_events_to ON chat_events (to_account) WHERE to_account IS NOT NULL;
