-- 0001: the baseline, on Postgres (M143): SQLite's 0001 in Postgres's
-- words. Plain Postgres, nothing beyond what's built in (aru-077). Postgres
-- starts empty, so this always runs; M145 copies production's rows in. The
-- column notes are SQLite's (migrations/sqlite/0001_baseline.sql); what
-- differs is noted here:
--
-- - SQLite's INTEGER is BIGINT (milliseconds, counts, numbers), and BOOLEAN
--   where it holds 0 or 1. BLOB is BYTEA.
-- - Text is `COLLATE pg_c_utf8` (Postgres 17's built-in C.UTF-8), whatever
--   the database's locale: it sorts and compares by code point, as SQLite
--   does by bytes, and its character classes know every letter (`search`).
-- - `chat_messages.id` is an identity, given by default so M145 can copy
--   SQLite's ids. Chat's search is a generated `tsvector` column and its GIN
--   index, not FTS5's `chat_fts` and its triggers (`db::chat`).
-- - SQLite's implicit `rowid`, which two queries order by, is a column of
--   that name on the two tables they read.
-- - Cloud secrets are keyed by project, not account (#1160).
--
-- Never edit a migration that has shipped: its checksum is recorded, and a
-- changed one stops the platform at start. Add the next number instead.

-- ---- billing
CREATE TABLE billing (
    owner TEXT COLLATE pg_c_utf8 PRIMARY KEY,
    customer TEXT COLLATE pg_c_utf8,
    subscription TEXT COLLATE pg_c_utf8,
    status TEXT COLLATE pg_c_utf8 NOT NULL,
    seat_item TEXT COLLATE pg_c_utf8,
    updated BIGINT NOT NULL
);
CREATE TABLE reported (
    account TEXT COLLATE pg_c_utf8 PRIMARY KEY,
