);

-- ---- chat
CREATE TABLE chat_rooms (
    id TEXT COLLATE pg_c_utf8 PRIMARY KEY,
    scope TEXT COLLATE pg_c_utf8 NOT NULL,
    kind TEXT COLLATE pg_c_utf8 NOT NULL,
    name TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT '',
    machine TEXT COLLATE pg_c_utf8,
    target TEXT COLLATE pg_c_utf8,
    created_by TEXT COLLATE pg_c_utf8 NOT NULL,
    created BIGINT NOT NULL,
    archived BIGINT,
    last_seq BIGINT NOT NULL DEFAULT 0,
    bytes BIGINT NOT NULL DEFAULT 0,
    project_id TEXT COLLATE pg_c_utf8
);
CREATE INDEX chat_rooms_scope ON chat_rooms (scope);
CREATE UNIQUE INDEX chat_rooms_target ON chat_rooms (kind, machine, target) WHERE machine IS NOT NULL;
CREATE UNIQUE INDEX chat_rooms_channel ON chat_rooms (scope, name) WHERE kind = 'channel';
CREATE TABLE chat_members (
    room TEXT COLLATE pg_c_utf8 NOT NULL,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    from_ms BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (room, account)
);
CREATE INDEX chat_members_account ON chat_members (account);
-- `search` is what chat's search matches (`db::chat::Search`): the text and
-- the quote, every run of characters that aren't letters or digits made a
-- space first, so words split where FTS5's unicode61 splits them (`main.rs`
-- is `main` and `rs`), then lowercased as they are (`simple`: no stemming,
-- no stop words).
CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room TEXT COLLATE pg_c_utf8 NOT NULL,
    seq BIGINT NOT NULL,
    author TEXT COLLATE pg_c_utf8 NOT NULL,
    at BIGINT NOT NULL,
    text TEXT COLLATE pg_c_utf8 NOT NULL,
    quote TEXT COLLATE pg_c_utf8,
    ref_machine TEXT COLLATE pg_c_utf8,
    ref_pane TEXT COLLATE pg_c_utf8,
    mentions TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT '[]',
    edited BIGINT,
    deleted BIGINT,
    imported TEXT COLLATE pg_c_utf8,
    imported_id BIGINT,
    search TSVECTOR GENERATED ALWAYS AS (
        to_tsvector('simple', regexp_replace(text || ' ' || coalesce(quote, ''), '[^[:alnum:]]+', ' ', 'g'))
    ) STORED,
    UNIQUE (room, seq)
);
CREATE INDEX chat_messages_author ON chat_messages (author);
CREATE INDEX chat_messages_search ON chat_messages USING GIN (search);
CREATE TABLE chat_reads (
    room TEXT COLLATE pg_c_utf8 NOT NULL,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    seq BIGINT NOT NULL DEFAULT 0,
    muted BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (room, account)
);
CREATE INDEX chat_reads_account ON chat_reads (account);
CREATE TABLE chat_readers (
    machine TEXT COLLATE pg_c_utf8 NOT NULL,
    kind TEXT COLLATE pg_c_utf8 NOT NULL,
    target TEXT COLLATE pg_c_utf8 NOT NULL,
    readers TEXT COLLATE pg_c_utf8 NOT NULL,
    at BIGINT NOT NULL,
    PRIMARY KEY (machine, kind, target)
);

-- ---- Cloud
CREATE TABLE cloud_agents (
    id TEXT COLLATE pg_c_utf8 PRIMARY KEY,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    version BIGINT NOT NULL,
    definition TEXT COLLATE pg_c_utf8 NOT NULL,
    archived BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX cloud_agents_owner ON cloud_agents (account);
CREATE TABLE cloud_runs (
    id TEXT COLLATE pg_c_utf8 PRIMARY KEY,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    request_key TEXT COLLATE pg_c_utf8 NOT NULL,
    spec TEXT COLLATE pg_c_utf8 NOT NULL,
    state TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT 'queued',
    provider_id TEXT COLLATE pg_c_utf8,
    created BIGINT NOT NULL,
    deadline BIGINT NOT NULL,
    result TEXT COLLATE pg_c_utf8,
    UNIQUE (account, request_key)
);
CREATE INDEX cloud_runs_owner ON cloud_runs (account, created);
-- Keyed by project (SQLite's are keyed by account, with the project beside
-- it): a secret belongs to its owner's personal project (M129), and a
-- project's secrets are what a Cloud workspace in it may use. `account` is
-- still who sealed it, which the seal is bound to (`cloud::secrets`), and
-- what's looked up by.
CREATE TABLE cloud_secrets (
    project_id TEXT COLLATE pg_c_utf8 NOT NULL,
    name TEXT COLLATE pg_c_utf8 NOT NULL,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    sealed BYTEA NOT NULL,
    PRIMARY KEY (project_id, name)
);
CREATE INDEX cloud_secrets_account ON cloud_secrets (account, name);
CREATE TABLE cloud_run_secrets (
    run TEXT COLLATE pg_c_utf8 NOT NULL REFERENCES cloud_runs (id),
    name TEXT COLLATE pg_c_utf8 NOT NULL,
    sealed BYTEA NOT NULL,
    PRIMARY KEY (run, name)
);
CREATE TABLE cloud_jobs (
    id TEXT COLLATE pg_c_utf8 PRIMARY KEY,
    kind TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT 'run',
    body TEXT COLLATE pg_c_utf8 NOT NULL,
    cancel BOOLEAN NOT NULL DEFAULT FALSE,
    lease TEXT COLLATE pg_c_utf8,
    lease_until BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE cloud_requests (
    conversation TEXT COLLATE pg_c_utf8 NOT NULL,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    id TEXT COLLATE pg_c_utf8 NOT NULL,
    body TEXT COLLATE pg_c_utf8 NOT NULL,
    pending BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (conversation, id)
);
CREATE TABLE cloud_notifications (
    conversation TEXT COLLATE pg_c_utf8 NOT NULL,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    request TEXT COLLATE pg_c_utf8 NOT NULL,
    delivered BOOLEAN NOT NULL DEFAULT FALSE,
    next_attempt BIGINT NOT NULL DEFAULT 0,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (conversation, request)
);
CREATE TABLE cloud_events (
    conversation TEXT COLLATE pg_c_utf8 NOT NULL,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    cursor BIGINT NOT NULL,
    body TEXT COLLATE pg_c_utf8 NOT NULL,
    PRIMARY KEY (conversation, cursor)
);
CREATE TABLE cloud_workspaces (
    id TEXT COLLATE pg_c_utf8 PRIMARY KEY,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    request_key TEXT COLLATE pg_c_utf8 NOT NULL,
    name TEXT COLLATE pg_c_utf8 NOT NULL,
    saved_spec TEXT COLLATE pg_c_utf8 NOT NULL,
    saved_revision TEXT COLLATE pg_c_utf8,
    built_spec TEXT COLLATE pg_c_utf8,
    status TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT 'provisioning',
    sandbox_status TEXT COLLATE pg_c_utf8,
    error TEXT COLLATE pg_c_utf8,
    revision TEXT COLLATE pg_c_utf8,
    built_from_revision TEXT COLLATE pg_c_utf8,
    stale BOOLEAN NOT NULL DEFAULT FALSE,
    changed_fields TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT '[]',
    environment TEXT COLLATE pg_c_utf8,
    vault TEXT COLLATE pg_c_utf8,
    provider_id TEXT COLLATE pg_c_utf8,
    created BIGINT NOT NULL,
    deleted BIGINT,
    settings_applied BOOLEAN NOT NULL DEFAULT TRUE,
    vault_secrets TEXT COLLATE pg_c_utf8,
    rebuild TEXT COLLATE pg_c_utf8,
    rebuild_error TEXT COLLATE pg_c_utf8,
    rebuilds BIGINT NOT NULL DEFAULT 0,
    setup_step TEXT COLLATE pg_c_utf8,
    project_id TEXT COLLATE pg_c_utf8,
    UNIQUE (account, request_key)
);
CREATE INDEX cloud_workspaces_owner ON cloud_workspaces (account, created);
CREATE TABLE cloud_workspace_specs (
    cloud_workspace TEXT COLLATE pg_c_utf8 NOT NULL,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    revision TEXT COLLATE pg_c_utf8 NOT NULL,
    spec TEXT COLLATE pg_c_utf8 NOT NULL,
    saved BIGINT NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (cloud_workspace, revision)
);
CREATE TABLE cloud_tabs (
    id TEXT COLLATE pg_c_utf8 PRIMARY KEY,
    account TEXT COLLATE pg_c_utf8 NOT NULL,
    cloud_workspace TEXT COLLATE pg_c_utf8 NOT NULL REFERENCES cloud_workspaces (id),
    request_key TEXT COLLATE pg_c_utf8 NOT NULL,
    spec TEXT COLLATE pg_c_utf8 NOT NULL,
    status TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT 'opening',
    error TEXT COLLATE pg_c_utf8,
    started BOOLEAN NOT NULL DEFAULT FALSE,
    provider_id TEXT COLLATE pg_c_utf8,
    created BIGINT NOT NULL,
    closed BIGINT,
    relaunch TEXT COLLATE pg_c_utf8,
    UNIQUE (account, cloud_workspace, request_key)
);
CREATE INDEX cloud_tabs_owner ON cloud_tabs (cloud_workspace, created);

-- ---- projects, team members and grants
CREATE TABLE projects (
    id TEXT COLLATE pg_c_utf8 PRIMARY KEY,
    team_id TEXT COLLATE pg_c_utf8,
    account_id TEXT COLLATE pg_c_utf8,
    name TEXT COLLATE pg_c_utf8 NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at BIGINT NOT NULL,
    CHECK ((team_id IS NULL) != (account_id IS NULL))
);
CREATE UNIQUE INDEX projects_team_default ON projects (team_id)
    WHERE is_default AND team_id IS NOT NULL;
CREATE UNIQUE INDEX projects_account_default ON projects (account_id)
    WHERE is_default AND account_id IS NOT NULL;
CREATE TABLE team_members (
    team_id TEXT COLLATE pg_c_utf8 NOT NULL,
    account_id TEXT COLLATE pg_c_utf8 NOT NULL,
    role TEXT COLLATE pg_c_utf8 NOT NULL,
    name TEXT COLLATE pg_c_utf8 NOT NULL,
    roster_version BIGINT NOT NULL,
    PRIMARY KEY (team_id, account_id)
);
CREATE INDEX team_members_account ON team_members (account_id);
CREATE TABLE grants (
    id TEXT COLLATE pg_c_utf8 PRIMARY KEY,
    subject_kind TEXT COLLATE pg_c_utf8 NOT NULL,
    subject_id TEXT COLLATE pg_c_utf8 NOT NULL,
    power TEXT COLLATE pg_c_utf8 NOT NULL,
    scope_kind TEXT COLLATE pg_c_utf8 NOT NULL CHECK (scope_kind IN ('project', 'account')),
    scope_id TEXT COLLATE pg_c_utf8 NOT NULL,
    granted_by TEXT COLLATE pg_c_utf8 NOT NULL,
    created_at BIGINT NOT NULL,
    revoked_at BIGINT
);
CREATE UNIQUE INDEX grants_live ON grants (subject_kind, subject_id, power, scope_kind, scope_id)
    WHERE revoked_at IS NULL;
CREATE INDEX grants_scope ON grants (scope_kind, scope_id);

CREATE INDEX cloud_workspaces_project ON cloud_workspaces (project_id);
CREATE INDEX chat_rooms_project ON chat_rooms (project_id);
