-- 0009: native issues (M194, platform step 6, #1263). A project's own
-- issues, numbered per project, with a timeline and full-text search.
-- Their comments aren't here: they're the messages of the issue's object
-- thread (`chat_rooms` with `kind = 'object'`, M196). Times are
-- milliseconds since the epoch. JSON lists are text.
-- SQLite's file in Postgres's words: `BIGINT` for its integers, identities
-- given by default so a window can copy SQLite's, `COLLATE pg_c_utf8`
-- text, and search as a generated `tsvector` column and its GIN index, not
-- FTS5's `issues_fts` and its triggers.

-- The last number a project gave an issue: bumped in the same transaction
-- as the issue's insert, so numbers have no gaps and no duplicates.
ALTER TABLE projects ADD COLUMN last_issue BIGINT NOT NULL DEFAULT 0;

-- An issue. `id` is the platform's (`iss_` and 32 hex characters); `number`
-- is the project's. `state` is `open` or `closed`, and a closed one has a
-- reason (`completed`, `not_planned` or `duplicate`) and a time. `author`
-- is the person's account; an agent's issue keeps its owner's account
-- there and names its machine in `author_agent`. `labels` and `assignees`
-- (accounts) are JSON lists. `github_repo` (`owner/name`), `github_repo_id`
-- and `github_number` say where it was exported to (M205). `search_id` is
-- SQLite's FTS5 rowid, kept so the two hold the same rows. `search` is
-- what search matches, the title and the body made words as chat's are
-- (`chat_messages.search`).
CREATE TABLE issues (
    search_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT COLLATE pg_c_utf8 NOT NULL UNIQUE,
    project_id TEXT COLLATE pg_c_utf8 NOT NULL,
    number BIGINT NOT NULL,
    title TEXT COLLATE pg_c_utf8 NOT NULL,
    body TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT '',
    state TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT 'open' CHECK (state IN ('open', 'closed')),
    close_reason TEXT COLLATE pg_c_utf8 CHECK (close_reason IN ('completed', 'not_planned', 'duplicate')),
    author TEXT COLLATE pg_c_utf8 NOT NULL,
    author_agent TEXT COLLATE pg_c_utf8,
    labels TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT '[]',
    assignees TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT '[]',
    github_repo TEXT COLLATE pg_c_utf8,
    github_repo_id BIGINT,
    github_number BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    closed_at BIGINT,
    search TSVECTOR GENERATED ALWAYS AS (
        to_tsvector('simple', regexp_replace(title || ' ' || body, '[^[:alnum:]]+', ' ', 'g'))
    ) STORED,
    UNIQUE (project_id, number),
    CHECK ((state = 'open') = (close_reason IS NULL AND closed_at IS NULL)),
    CHECK ((state = 'closed') = (close_reason IS NOT NULL AND closed_at IS NOT NULL))
);
CREATE INDEX issues_state ON issues (project_id, state, number);
CREATE INDEX issues_author ON issues (author);
CREATE INDEX issues_search ON issues USING GIN (search);

-- An issue's timeline: `kind` is `opened`, `edited`, `closed`, `reopened`,
-- `labelled`, `unlabelled`, `assigned`, `unassigned` or `exported`. `actor`
-- is who did it (an agent: its owner's account, and its machine in
-- `actor_agent`). `detail` is a small JSON object: an edit's old title, a
-- close's reason, the label or assignee, where it was exported to
-- (`db::issues::Event`). `id` orders them: an issue's are written with its
-- row locked, so they commit in order.
CREATE TABLE issue_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id TEXT COLLATE pg_c_utf8 NOT NULL,
    kind TEXT COLLATE pg_c_utf8 NOT NULL,
    actor TEXT COLLATE pg_c_utf8 NOT NULL,
    actor_agent TEXT COLLATE pg_c_utf8,
    at BIGINT NOT NULL,
    detail TEXT COLLATE pg_c_utf8 NOT NULL DEFAULT '{}'
);
CREATE INDEX issue_events_issue ON issue_events (issue_id, id);
CREATE INDEX issue_events_actor ON issue_events (actor);
