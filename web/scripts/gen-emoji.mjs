// Writes src/shared/chat/emoji-data.ts from gemoji's db/emoji.json (MIT,
// github.com/github/gemoji): `node scripts/gen-emoji.mjs path/to/emoji.json`.
// Re-run it to take a newer Unicode; the output is committed, nothing is
// fetched at build or run time.

import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(process.argv[2], "utf8"));
const order = [];
const by = new Map();
for (const e of src) {
  if (!by.has(e.category)) {
    by.set(e.category, []);
    order.push(e.category);
  }
  // One line each: the character, its shortcodes, then words that find it.
  by.get(e.category).push(`${e.emoji} ${e.aliases.join(",")} ${[...new Set([...e.tags, ...e.description.split(/\s+/)])].join(" ").toLowerCase()}`.trimEnd());
}
const body = order.map((c) => `# ${c}\n${by.get(c).join("\n")}`).join("\n");
writeFileSync(
  new URL("../src/shared/chat/emoji-data.ts", import.meta.url),
  `// Generated by scripts/gen-emoji.mjs from gemoji (MIT, GitHub): do not edit.
// A "# Category" line, then one emoji per line: the character, its
// shortcodes (comma-separated), and the words that find it.

export default \`${body.replace(/\\/g, "\\\\").replace(/`/g, "\\`")}\`;
`,
);
