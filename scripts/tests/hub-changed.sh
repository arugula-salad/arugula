#!/usr/bin/env bash
# The hub deploys only when what it's built from changed (scripts/ci-hub-changed,
# scripts/ci-control-deploy): in a small repository standing in for this
# one, `inputs` reads a dep-info as cargo writes it, `diff` sees a change to
# the hub's code, its pages, the lock file, the recipes or the platform's
# contract and not a bump, the daemon, the docs or the specs, and `deploy`
# skips the hub (saying so) or deploys it, against a fake flyctl. Nothing
# reaches the network or Fly.
#
#   scripts/tests/hub-changed.sh
set -euo pipefail

src=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
fail=0
bad() { printf 'FAIL  %s\n' "$*"; fail=1; }
ok() { printf 'ok    %s\n' "$*"; }
# check WHAT CMD...: CMD succeeds.
check() {
  local what=$1
  shift
  if "$@"; then ok "$what"; else bad "$what"; fi
}
# shellcheck disable=SC2329 # check runs it
lacks() { ! grep -qF -- "$1" "$2"; }

export GIT_AUTHOR_NAME=test GIT_AUTHOR_EMAIL=test@example.invalid GIT_COMMITTER_NAME=test GIT_COMMITTER_EMAIL=test@example.invalid
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
unset ARUGULA_HUB_DEPLOY GITHUB_STEP_SUMMARY

w=$tmp/work
mkdir -p "$w/scripts" "$w/packaging/control"
cp "$src/ci-hub-changed" "$src/ci-control-deploy" "$src/release" "$w/scripts/"
cp "$src/../packaging/control/fly.toml" "$src/../packaging/control/Dockerfile" "$w/packaging/control/"
cd "$w"
put() { mkdir -p "$(dirname "$1")"; printf '%s\n' "$2" >"$1"; }
# sed -i, on macOS too (in expect's changes).
# shellcheck disable=SC2329
subst() { sed "$1" "$2" >"$2.new" && mv "$2.new" "$2"; }
lock() { # VERSION SERDE
  printf '%s\n' '# This file is automatically @generated by Cargo.' 'version = 4' '' \
    '[[package]]' 'name = "arugula-control"' "version = \"$1\"" 'dependencies = [' ' "serde",' ']' '' \
    '[[package]]' 'name = "arugulad"' "version = \"$1\"" '' \
    '[[package]]' 'name = "serde"' "version = \"$2\"" 'source = "registry+https://github.com/rust-lang/crates.io-index"' >Cargo.lock
}
put Cargo.toml $'[workspace]\nmembers = ["crates/*"]\n\n[workspace.package]\nversion = "1.0.0"\nedition = "2024"'
lock 1.0.0 1.0.0
put THIRD_PARTY.md '- [arugula-control 1.0.0](https://example.invalid)'
put crates/control/Cargo.toml $'[package]\nname = "arugula-control"\nversion.workspace = true\n\n[dependencies]\nserde = "1"'
put crates/control/routes.toml '[[route]]'
put crates/control/src/main.rs 'fn main() {}'
put crates/control/src/main_tests.rs '#[test] fn t() {}'
put crates/platform/Cargo.toml $'[package]\nname = "arugula-platform"\nversion.workspace = true'
put crates/platform/src/lib.rs 'pub mod more;'
put crates/platform-api/src/hub.rs 'pub trait HubPort {}'
put crates/daemon/Cargo.toml $'[package]\nname = "arugulad"\nversion.workspace = true'
put crates/daemon/src/main.rs 'fn main() {}'
put crates/proto/fixtures/attach.jsonl '{}'
put web/src/app.ts 'export {};'
put web/e2e/app.spec.ts 'test();'
put web/dev-control.ts '// dev server'
put web/package.json '{}'
put docs/control-ops.md '# Ops'
put justfile $'# Builds.\nstatic arch="x86_64": web\n    cargo build --release\n\nweb:\n    cd web && pnpm run build\n\n# Not the hub\'s.\ntest:\n    cargo nextest run'
git init -q -b main .
git add -A
git commit -qm one
git tag -a v1.0.0 -m v1.0.0

# A dep-info as cargo writes it beside the binary: the workspace's files,
# the embedded pages (built, not in git), a registry crate and a build
# script's output, which aren't the hub's inputs by path.
export CARGO_TARGET_DIR=$tmp/target
dep=$tmp/target/release/arugula-control.d
mkdir -p "$(dirname "$dep")"
printf '%s: %s %s %s %s %s %s\n' "$tmp/target/release/arugula-control" \
  "$w/crates/control/routes.toml" "$w/crates/control/src/main.rs" "$w/crates/platform/src/lib.rs" \
  "$w/web/dist/index.html" "$tmp/home/.cargo/registry/src/serde-1.0.0/src/lib.rs" \
  "$tmp/target/release/build/arugula-x/out/gen.rs" >"$dep"
scripts/ci-hub-changed inputs "$dep" >"$tmp/inputs"
for want in crates/control/src/main.rs crates/control/Cargo.toml crates/control/routes.toml crates/platform/src/lib.rs \
  crates/platform-api web ':(exclude)web/e2e' Cargo.lock recipe:static packaging/control; do
  check "inputs has $want" grep -qxF -- "$want" "$tmp/inputs"
done
for not in crates/daemon/src/main.rs crates/control/src/main_tests.rs web/dist/index.html serde gen.rs; do
  check "inputs hasn't $not" lacks "$not" "$tmp/inputs"
done
scripts/ci-hub-changed inputs "$tmp/nothing.d" >"$tmp/whole" 2>/dev/null
check "no dep-info: the whole tree" grep -qx . "$tmp/whole"
printf '%s: %s\n' "$tmp/target/release/arugula-control" "/elsewhere/crates/control/src/main.rs" >"$tmp/elsewhere.d"
scripts/ci-hub-changed inputs "$tmp/elsewhere.d" >"$tmp/whole" 2>/dev/null
check "a dep-info of another checkout: the whole tree" grep -qx . "$tmp/whole"

# expect WANT NAME CHANGE: on a branch from v1.0.0, CHANGE (shell) and a
# commit; then diff's exit status is WANT (0 changed, 1 not).
expect() {
  local want=$1 name=$2 change=$3 got=0
  git checkout -q -B "t-$RANDOM" v1.0.0
  eval "$change"
  git add -A
  git commit -qm "$name"
  scripts/ci-hub-changed diff v1.0.0 HEAD "$tmp/inputs" >"$tmp/out" 2>&1 || got=$?
  if [ "$got" = "$want" ]; then ok "$name: $(paste -sd' ' "$tmp/out")"
  else bad "$name: exit $got, wanted $want: $(cat "$tmp/out")"; fi
}
bump='subst "s/^version = \"1.0.0\"/version = \"1.0.1\"/" Cargo.toml; lock 1.0.1 1.0.0; subst "s/arugula-control 1.0.0/arugula-control 1.0.1/" THIRD_PARTY.md; put crates/proto/fixtures/releases/1.0.1/attach.jsonl "{}"; put docs/releases/1.0.1.md notes'
expect 1 "a bump" "$bump"
expect 1 "the daemon" 'put crates/daemon/src/main.rs "fn main() { run() }"'
expect 1 "the docs" 'put docs/control-ops.md "# Ops, more"'
expect 1 "the specs and a dev server" 'put web/e2e/app.spec.ts "test(2);"; put web/dev-control.ts "// more"'
expect 1 "a test of the hub's" 'put crates/control/src/main_tests.rs "#[test] fn u() {}"'
expect 1 "another recipe" 'subst "s/nextest run/nextest run --all/" justfile'
expect 0 "the hub's code" 'put crates/control/src/main.rs "fn main() { serve() }"'
expect 0 "its routes" 'put crates/control/routes.toml "[[route]] # more"'
expect 0 "the platform it links" 'put crates/platform/src/lib.rs "pub mod more; pub mod most;"'
expect 0 "the platform's contract" 'put crates/platform-api/src/hub.rs "pub trait HubPort { fn more(); }"'
expect 0 "its pages" 'put web/src/app.ts "export const a = 1;"'
expect 0 "a registry crate" 'lock 1.0.0 1.0.1'
# shellcheck disable=SC2016 # expanded by expect's eval
expect 0 "the daemon's manifest (features are shared)" 'put crates/daemon/Cargo.toml "$(cat crates/daemon/Cargo.toml; printf "\n[dependencies]\nserde = \"1\"")"'
expect 0 "the static recipe" 'subst "s/cargo build --release/cargo build --release --locked/" justfile'
expect 0 "its image" 'echo "# more" >>packaging/control/Dockerfile'
expect 0 "a bump and the hub's code" "$bump; put crates/control/src/main.rs 'fn main() { serve() }'"

# ci-control-deploy, against a fake flyctl whose machines run what
# $tmp/fly/running says (one image label a line) and a fake curl.
git checkout -q main
git tag -a v0.9.0 -m v0.9.0 'v1.0.0^{}' # an older release, for the machines on two
mkdir -p "$tmp/bin" "$tmp/fly"
cat >"$tmp/bin/flyctl" <<'EOF'
#!/usr/bin/env bash
case "$1" in
  status)
    jq -nc --rawfile r "$FAKE_FLY/running" '{Machines: [$r | split("\n")[] | select(. != "") | {id: "m1", state: "started", config: {metadata: {fly_process_group: "app"}}, image_ref: {tag: .}, checks: [{status: "passing"}]}]}' ;;
  deploy)
    echo "deploy $*" >>"$FAKE_FLY/log"
    while [ $# -gt 0 ]; do [ "$1" = --image-label ] && echo "$2" >"$FAKE_FLY/running"; shift; done ;;
  *) echo "fake flyctl: $*" >&2; exit 1 ;;
esac
EOF
printf '#!/bin/sh\necho %s\n' "'{\"control\": true}'" >"$tmp/bin/curl"
chmod +x "$tmp/bin/flyctl" "$tmp/bin/curl"
export FAKE_FLY=$tmp/fly FLY_API_TOKEN=fake PATH=$tmp/bin:$PATH

# Releases on top of v1.0.0: v1.0.1 a bump and a daemon change, v1.0.2 the
# hub's code.
git checkout -q -B rel v1.0.0
eval "$bump"
put crates/daemon/src/main.rs 'fn main() { run() }'
git add -A && git commit -qm 1.0.1 && git tag -a v1.0.1 -m v1.0.1
put crates/control/src/main.rs 'fn main() { serve() }'
git add -A && git commit -qm 1.0.2 && git tag -a v1.0.2 -m v1.0.2
git init -q --bare "$tmp/origin.git"
git push -q "$tmp/origin.git" --tags rel

# deploy WANT NAME RUNNING TAG [ENV...]: a shallow clone of TAG, as the
# job's checkout, deploys it with its hub-inputs while the hub runs
# RUNNING; WANT is deployed or skipped.
bins=$tmp/bins
mkdir -p "$bins"
echo binary >"$bins/arugula-control"
deploy() {
  local want=$1 name=$2 running=$3 tag=$4 c got rc=0
  shift 4
  c=$tmp/clone-$RANDOM
  git clone -q --depth=1 --branch "$tag" "file://$tmp/origin.git" "$c" 2>/dev/null
  printf '%s\n' "$running" >"$tmp/fly/running"
  rm -f "$tmp/fly/log" "$tmp/summary"
  : >"$tmp/summary"
  env GITHUB_STEP_SUMMARY="$tmp/summary" "$@" "$c/scripts/ci-control-deploy" deploy "$tag" "$bins" >"$tmp/out" 2>&1 || rc=$?
  if [ -s "$tmp/fly/log" ]; then got=deployed; else got=skipped; fi
  if [ "$rc" = 0 ] && [ "$got" = "$want" ]; then ok "deploy $name: $want: $(grep -m1 -E 'notice|deploying the hub' "$tmp/out")"
  else bad "deploy $name: exit $rc, $got, wanted $want: $(cat "$tmp/out")"; fi
}
cp "$tmp/inputs" "$bins/hub-inputs"
deploy skipped "a bump and the daemon" v1.0.0 v1.0.1
check "the summary says so" grep -q 'hub unchanged since v1.0.0: not deployed' "$tmp/summary"
check "the summary says how to deploy anyway" grep -q 'ARUGULA_HUB_DEPLOY' "$tmp/summary"
# v1.0.1 was skipped: v1.0.2 is compared with v1.0.0, which the hub runs.
deploy deployed "the hub's code, after a skipped release" v1.0.0 v1.0.2
check "the summary says it deployed" grep -q 'The hub: deploying v1.0.2' "$tmp/summary"
deploy skipped "the release it runs" v1.0.2 v1.0.2
deploy deployed "ARUGULA_HUB_DEPLOY=always" v1.0.0 v1.0.1 ARUGULA_HUB_DEPLOY=always
deploy deployed "over a hotfix" deployment-01JABCDEF v1.0.1
deploy deployed "machines on two releases" $'v1.0.0\nv0.9.0' v1.0.1
deploy skipped "an older tag than it runs" v2.0.0 v1.0.1
check "says it runs a newer one" grep -q 'newer than v1.0.1' "$tmp/out"
rm "$bins/hub-inputs"
deploy deployed "without hub-inputs" v1.0.0 v1.0.1

exit $fail
